#!/usr/bin/env node
// Builds frontend/src/lib/exercises-data.js from catalogue/, openGym's own exercise catalogue.
//
//   node scripts/catalogue/build.mjs
//
// This fork predates the catalogue: its app still reads the older EXDB row shape, with the
// instruction steps inline (`st`) and one "delts" target instead of front/side/rear. Rather than
// port every consumer, the catalogue is folded INTO that shape here:
//
//   - The 1,324 exercises the fork always had keep their row exactly as it was (name, muscles,
//     steps), so nothing a logged workout, a routine or a translation pack relies on moves. Only
//     their media file names change, and they gain the catalogue's description.
//   - Every other catalogue exercise becomes a new row. New rows carry `cat` (the catalogue's
//     category), which is also how a re-run tells them from the old ones: a row without `cat` is
//     kept, a row with it is rebuilt from the catalogue.
//   - A female drawing of an exercise (`variantOf`) is not an exercise of its own and is left out.
//
// The stills and clips themselves are not touched by this script; see catalogue/media/NOTICE.md.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const DIR = path.join(ROOT, 'catalogue/exercises')
const OUT = path.join(ROOT, 'frontend/src/lib/exercises-data.js')

const catalogue = fs.readdirSync(DIR).filter(f => f.endsWith('.json')).sort()
  .map(f => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')))

const src = fs.readFileSync(OUT, 'utf8')
const start = src.indexOf('export const EXDB=') + 'export const EXDB='.length
const current = src.slice(start).trimStart().startsWith('JSON.parse(')
  ? (await import(OUT + '?t=' + Date.now())).EXDB
  : JSON.parse(src.slice(src.indexOf('[', start), src.lastIndexOf(']') + 1))
const kept = new Map(current.filter(r => !r.cat).map(r => [r.id, r]))

// The catalogue splits the shoulder into three heads; the fork's body map draws one.
const TARGET = { 'front delts': 'delts', 'side delts': 'delts', 'rear delts': 'delts' }
// The catalogue's muscle-map names, where they differ from the fork's (lib/muscles.js MUSCLES).
const SLUG = { 'front-delts': 'deltoids', 'side-delts': 'deltoids', 'rear-delts': 'deltoids', lats: 'upper-back' }
const slugs = list => [...new Set((list || []).map(m => SLUG[m] || m))]

const rows = catalogue.filter(e => !e.variantOf).map(e => {
  const media = { img: e.id + '.webp', gif: e.id + '.mp4' }
  const old = kept.get(e.id)
  if (old) return { ...old, ...(e.description ? { desc: e.description } : {}), ...media }
  const row = {
    id: e.id, n: e.name, bp: e.bodyPart, eq: e.equipment, tg: TARGET[e.target] || e.target,
    mg: e.secondaryMuscles[0] || '', sm: e.secondaryMuscles, st: e.instructions,
    ...(e.description ? { desc: e.description } : {}), ...media, cat: e.category || 'strength',
  }
  if (e.hold) row.hd = 1
  if (e.muscleMap?.primaries) row.primaries = slugs(e.muscleMap.primaries)
  if (e.muscleMap?.secondaries) row.secondaries = slugs(e.muscleMap.secondaries).filter(m => !(row.primaries || []).includes(m))
  return row
}).sort((a, b) => (a.n < b.n ? -1 : a.n > b.n ? 1 : a.id < b.id ? -1 : 1))

const missing = [...kept.keys()].filter(id => !rows.some(r => r.id === id))
if (missing.length) { console.error('catalogue lost ids the app has always had: ' + missing.join(', ')); process.exit(1) }

// JSON.parse('…') rather than an object literal: an engine parses a JSON string noticeably
// faster than the same data as code, and this list is read on every start of the app.
const literal = "JSON.parse('" + JSON.stringify(rows).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
  .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + "')"
fs.writeFileSync(OUT, '// generated by scripts/catalogue/build.mjs from catalogue/ — do not edit\nexport const EXDB=' + literal + '\n')
console.log(`catalogue: ${rows.length} exercises (${kept.size} kept as they were, ${rows.length - kept.size} from the catalogue)`)
